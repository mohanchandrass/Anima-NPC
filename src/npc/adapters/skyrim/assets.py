"""Bounded screenshot artifacts and verified PCM WAV staging."""

import io
import json
import os
from pathlib import Path
import struct
import threading
from itertools import islice
import wave
import zlib


MAX_WAV_BYTES = 6 * 1024 * 1024


def atomic_write(path: Path, data: bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    try:
        temporary.write_bytes(data)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def wav_duration(raw: bytes) -> float:
    if len(raw) > MAX_WAV_BYTES:
        raise ValueError("audio exceeds 6 MB")
    try:
        with wave.open(io.BytesIO(raw), "rb") as audio:
            duration = audio.getnframes() / audio.getframerate()
            if (audio.getcomptype() != "NONE" or audio.getsampwidth() != 2
                    or audio.getnchannels() not in (1, 2) or not 8000 <= audio.getframerate() <= 48000
                    or not 0 < duration <= 30):
                raise ValueError("expected 1-30 seconds of PCM16 mono/stereo WAV")
            expected = audio.getnframes() * audio.getnchannels() * 2
            if len(audio.readframes(audio.getnframes())) != expected:
                raise ValueError("truncated audio")
            return duration
    except (wave.Error, EOFError, ZeroDivisionError):
        raise ValueError("invalid WAV") from None


def read_audio(path: str, root: Path) -> bytes:
    candidate = Path(path)
    candidate = (candidate if candidate.is_absolute() else root / candidate).resolve()
    if not candidate.is_relative_to(root.resolve()) or candidate.suffix.lower() != ".wav":
        raise ValueError("audio path must be a WAV inside audio_root")
    with candidate.open("rb") as stream:
        raw = stream.read(MAX_WAV_BYTES + 1)
    wav_duration(raw)
    return raw


def stage_audio(raw: bytes, game_directory: Path, delivery_id: str):
    # IDs are generated by the bridge, never taken from filenames returned by a model.
    if len(delivery_id) != 32 or any(c not in "0123456789abcdef" for c in delivery_id):
        raise ValueError("invalid delivery ID")
    duration = wav_duration(raw)
    relative = f"Sound/Voice/AnimaConnector/{delivery_id}.wav"
    atomic_write(game_directory / "Data" / relative, raw)
    return relative, duration


def stage_playback(raw: bytes, output_directory: Path, delivery_id: str):
    """Write a WAV for system playback outside the game folder; returns (path, wav duration)."""
    if len(delivery_id) != 32 or any(c not in "0123456789abcdef" for c in delivery_id):
        raise ValueError("invalid delivery ID")
    duration = wav_duration(raw)
    path = output_directory / "speech" / "playback" / f"{delivery_id}.wav"
    atomic_write(path, raw)
    return path, duration


def mouth_envelope(raw: bytes) -> list[float]:
    """50 ms amplitude samples for approximate mouth motion, not phoneme timings."""
    wav_duration(raw)
    values = []
    with wave.open(io.BytesIO(raw), "rb") as audio:
        step = max(1, (audio.getframerate() + 19) // 20)
        while samples := audio.readframes(step):
            energy = sum(abs(value[0]) for value in struct.iter_unpack("<h", samples))
            values.append(round(min(1.0, 6 * energy / (32768 * (len(samples) // 2))), 3))
    return values


class Artifacts:
    def __init__(self, directory: Path, *, max_bytes: int, max_screenshots: int, capture):
        self.directory = directory
        self.max_bytes = max_bytes
        self.max_screenshots = max_screenshots
        self.capture = capture
        self._capture_gate = threading.Lock()

    def check_budget(self, additional=0):
        # Bounded by stop-admission; no deletion of pipeline handoff records.
        total = sum(p.stat().st_size for p in self.directory.rglob("*") if p.is_file()) if self.directory.exists() else 0
        if total + additional > self.max_bytes:
            raise ValueError("connector output budget exhausted; archive output before continuing")

    def event(self, identifier: str, payload: dict):
        if sum(1 for _ in islice((self.directory / "inbox").glob("*.json"), 4096)) >= 4096:
            raise ValueError("connector inbox limit reached; archive processed events")
        raw = json.dumps(payload, ensure_ascii=False, allow_nan=False).encode("utf-8")
        self.check_budget(len(raw))
        atomic_write(self.directory / "inbox" / f"{identifier}.json", raw)

    def screenshot(self, identifier: str, pid: int):
        directory = self.directory / "screenshots"
        directory.mkdir(parents=True, exist_ok=True)
        if not self._capture_gate.acquire(blocking=False):
            raise ValueError("game capture busy")
        try:
            raw = self.capture(pid)
        finally:
            self._capture_gate.release()
        if not raw.startswith(b"\x89PNG\r\n\x1a\n") or len(raw) > 32 * 1024**2:
            raise ValueError("invalid screenshot")
        old = sorted(directory.glob("frame-*.png"), key=lambda p: p.stat().st_mtime)
        # Frames are disposable, unlike handoff records, so they may hold only a share of the budget (real frames ~4 MB).
        kept_bytes = sum(p.stat().st_size for p in old)
        while old and (len(old) >= self.max_screenshots or kept_bytes + len(raw) > self.max_bytes // 4):
            oldest = old.pop(0)
            kept_bytes -= oldest.stat().st_size
            oldest.unlink()
        self.check_budget(len(raw))
        path = directory / f"frame-{identifier}.png"
        atomic_write(path, raw)
        return str(path.resolve())


def png_from_bgra(width: int, height: int, raw: bytes) -> bytes:
    if not 0 < width <= 4096 or not 0 < height <= 2160 or len(raw) != width * height * 4:
        raise ValueError("invalid frame dimensions")
    rows = bytearray()
    for offset in range(0, len(raw), width * 4):
        row = raw[offset:offset + width * 4]
        rows.append(0)
        rgb = bytearray(width * 3)
        rgb[0::3], rgb[1::3], rgb[2::3] = row[2::4], row[1::4], row[0::4]
        rows.extend(rgb)

    def chunk(kind, value):
        return struct.pack(">I", len(value)) + kind + value + struct.pack(">I", zlib.crc32(kind + value) & 0xffffffff)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(rows, 3)) + chunk(b"IEND", b""))
